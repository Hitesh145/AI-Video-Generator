"""Project-owned models for parsed research-paper PDFs."""

from __future__ import annotations

from typing import Literal
from uuid import uuid4

from pydantic import BaseModel, Field


BlockType = Literal[
    "title",
    "heading",
    "paragraph",
    "list_item",
    "table",
    "figure",
    "equation",
    "caption",
    "footnote",
    "code",
    "other",
]


class DocumentBlock(BaseModel):
    """One content block extracted from a source document."""

    block_id: str = Field(default_factory=lambda: str(uuid4()))
    ordinal: int = Field(ge=0, description="Zero-based position in reading order.")
    block_type: BlockType
    source_label: str = Field(
        description="Original parser label, retained for traceability."
    )
    text: str = Field(
        default="",
        description="Extracted text or a textual representation, if available.",
    )
    caption: str | None = Field(
        default=None,
        description="Extracted caption, when available; never generated by inference.",
    )
    image_asset_path: str | None = Field(
        default=None,
        description=(
            "Path to a successfully exported figure image, when available. "
            "This is an on-disk path, not embedded image bytes."
        ),
    )
    image_available: bool | None = Field(
        default=None,
        description=(
            "For figure blocks, whether an image asset was successfully exported. "
            "None for non-figure blocks or when image extraction was not attempted."
        ),
    )
    page_number: int | None = Field(default=None, ge=1)
    section_path: list[str] = Field(
        default_factory=list,
        description="Known heading hierarchy leading to this block.",
    )
    heading_level: int | None = Field(default=None, ge=1)
    is_document_metadata: bool = Field(
        default=False,
        description=(
            "Whether this block represents document-level metadata (for example, "
            "title, author, or affiliation) rather than lesson-source content."
        ),
    )
    metadata: dict[str, str | int | float | bool] = Field(default_factory=dict)


class NormalizedDocument(BaseModel):
    """Normalized PDF content independent of Docling's internal object model."""

    document_id: str = Field(default_factory=lambda: str(uuid4()))
    source_filename: str
    title: str | None = None
    authors: list[str] = Field(
        default_factory=list,
        description="Authors only when explicitly available from extraction.",
    )
    affiliations: list[str] = Field(
        default_factory=list,
        description=(
            "Author affiliations only when explicitly available from extraction."
        ),
    )
    page_count: int | None = Field(default=None, ge=1)
    parser_name: str = "docling"
    parser_version: str | None = None
    blocks: list[DocumentBlock] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
